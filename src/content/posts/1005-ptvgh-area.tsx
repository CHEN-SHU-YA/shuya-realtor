    <p>同一段原文，也順手更正了兩個流傳很廣的說法：</p>
    <ul>
      <li>
        <strong>官方用語是「全縣第一座擁有大型沙坑共融遊憩空間」</strong>
        ——不是「屏東縣第二座特色遊戲場」。後者只見於民間親子部落格與旅遊平台，官方新聞稿沒有這個排序用語。
