      <strong>這五款裡面，屏東老巷弄命中率最高的是第 4 款</strong>
      ——旁邊有兩戶以上編了門牌，而且門牌編釘或戶籍登記超過二十年。屏東市舊城區與各鄉鎮的老街廓，很多落在這一款上。
