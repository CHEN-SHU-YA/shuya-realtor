      <strong>但這些是「將來蓋房子時建築線要退到多寬」，不是「這條巷子現在有多寬」。</strong>
      巷子變寬的法定機制，是等旁邊的人蓋房子時退讓，不是政府去拓寬。查證時在屏東縣主管法規系統裡也沒有找到獨立的巷道拓寬自治條例或補助辦法。
